const itemImages = new Map<number, string>();
export function itemImage(index: number): string {
  const cached = itemImages.get(index); if (cached) return cached;
  const rects: string[] = [];
  drawItemArt((color, x, y, w, h) => rects.push(`<rect x="${Math.round(x)}" y="${Math.round(y)}" width="${Math.round(w)}" height="${Math.round(h)}" fill="${color}"/>`), index);
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 20 20" width="40" height="40" shape-rendering="crispEdges">${rects.join('')}</svg>`;
  const image = 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(svg); itemImages.set(index, image); return image;
}
