import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import crypto from 'node:crypto';
import solc from 'solc';

const root=path.resolve(import.meta.dirname,'../..');
const require=createRequire(path.join(root,'package.json'));
const sourcePath='contracts/NEARlyHuman.sol';
const source=fs.readFileSync(path.join(root,sourcePath),'utf8');
const input={language:'Solidity',sources:{[sourcePath]:{content:source}},settings:{optimizer:{enabled:true,runs:200},viaIR:true,evmVersion:'cancun',outputSelection:{'*':{'*':['abi','evm.bytecode.object','evm.deployedBytecode.object','metadata']}}}};
const output=JSON.parse(solc.compile(JSON.stringify(input),{import:requested=>{try{return{contents:fs.readFileSync(require.resolve(requested),'utf8')}}catch{return{error:'Import unavailable: '+requested}}}}));
for(const e of output.errors||[])if(e.severity==='error')process.stderr.write(e.formattedMessage+'\n');
if((output.errors||[]).some(e=>e.severity==='error'))process.exit(1);
const contract=output.contracts[sourcePath].NEARlyHuman;
const artifact={contractName:'NEARlyHuman',sourceName:sourcePath,compiler:solc.version(),evmVersion:'cancun',sourceSha256:crypto.createHash('sha256').update(source).digest('hex'),abi:contract.abi,bytecode:'0x'+contract.evm.bytecode.object,deployedBytecode:'0x'+contract.evm.deployedBytecode.object};
fs.mkdirSync(path.join(root,'contracts/artifacts'),{recursive:true});
fs.writeFileSync(path.join(root,'contracts/artifacts/NEARlyHuman.json'),JSON.stringify(artifact,null,2)+'\n');
fs.mkdirSync(path.join(root,'src/chain'),{recursive:true});
fs.writeFileSync(path.join(root,'src/chain/abi.ts'),'// Generated by scripts/chain/build-contract.mjs from the Solidity source.\nexport const nearlyHumanAbi = '+JSON.stringify(contract.abi,null,2)+' as const;\n');
const runtimeBytes=contract.evm.deployedBytecode.object.length/2;
if(runtimeBytes>24576)throw Error('Runtime exceeds EIP-170: '+runtimeBytes);
console.log(JSON.stringify({compiler:artifact.compiler,runtimeBytes,initBytes:contract.evm.bytecode.object.length/2,sourceSha256:artifact.sourceSha256}));
