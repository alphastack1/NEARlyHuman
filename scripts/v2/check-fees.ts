import assert from 'node:assert/strict';
import { calculateV2ProcessingFee } from '../../server/v2/quotes';
const base = { requestGas: 1200000n, relayGas: 6000000n, gasPrice: 10000000n, inferenceReserveWei: 1000n, hostingReserveWei: 2000n };
const two = calculateV2ProcessingFee({ ...base, multiplier: 2 });
const three = calculateV2ProcessingFee({ ...base, multiplier: 3 });
assert.equal(two.processingFee, two.relayReserve + 3000n);
assert.equal(three.processingFee, (two.processingFee * 3n + 1n) / 2n);
assert(three.processingFee > two.processingFee);
assert.equal(calculateV2ProcessingFee({ ...base, multiplier: 1 }).processingFee, two.processingFee);
assert.equal(two.totalEstimate, two.networkEstimate + two.processingFee);
for (const multiplier of [0, 21, 2.5]) assert.throws(() => calculateV2ProcessingFee({ ...base, multiplier }));
assert.throws(() => calculateV2ProcessingFee({ ...base, multiplier: 2, inferenceReserveWei: -1n }));
console.log(JSON.stringify({ scope: 'Integer quote math only; no transactions or exchange-rate claim.', tests: 9, baselineProcessingWei: two.processingFee.toString(), increasedProcessingWei: three.processingFee.toString(), passed: true }));
